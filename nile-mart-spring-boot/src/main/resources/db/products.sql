-- Oracle (23ai or newer) script for the products table.
-- Column names match the Product entity and JdbcProductDao.
-- WARNING: running this script deletes the existing products table and all its data.

DROP TABLE IF EXISTS products;

CREATE TABLE products (
    id        NUMBER(10)          GENERATED BY DEFAULT AS IDENTITY,
    name      VARCHAR2(200 CHAR)  NOT NULL,
    category  VARCHAR2(100 CHAR)  NOT NULL,
    price     NUMBER(12, 2)       NOT NULL,
    in_stock  NUMBER(10)          NOT NULL,
    active    VARCHAR2(5 CHAR)    NOT NULL,
    CONSTRAINT pk_products          PRIMARY KEY (id),
    CONSTRAINT ck_products_price    CHECK (price > 0),
    CONSTRAINT ck_products_in_stock CHECK (in_stock >= 0),
    CONSTRAINT ck_products_active   CHECK (active IN ('true', 'false'))
);

